
import { useEffect, useState } from 'react'
import {
  AlertTriangle,
  ArrowRight,
  BrainCircuit,
  CheckCircle2,
  FileSearch,
  ShieldAlert,
} from 'lucide-react'

type Finding = {
  ruleId: string
  category: string
  observation: string
  evidenceNodeIds: string[]
  details: Record<string, unknown>
}

type Hypothesis = {
  category: string
  status: string
  summary: string
  supportingRuleIds: string[]
  evidenceNodeIds: string[]
  limitations: string[]
}

type EvaluationSnapshot = {
  caseId: string
  datasetProvenance: string
  evaluationMode: string
  traceSha256: string
  summary: {
    traceId: string
    outcome: string
    categories: string[]
    observationCount: number
    hypothesisCount: number
    judgeStatus: string
    warnings: string[]
  }
  attribution: {
    ruleReport: {
      observations: Finding[]
      hypotheses: Hypothesis[]
      warnings: string[]
    }
    judgeStatus: string
    judgment: unknown | null
    warnings: string[]
  }
}

const cases = [
  { id: 'workflow-001', label: 'Mandatory verification skipped' },
  { id: 'workflow-002', label: 'Optional verification' },
  { id: 'workflow-003', label: 'Environment interruption' },
  { id: 'workflow-004', label: 'Patch tool failure' },
  { id: 'workflow-005', label: 'Test assertion failure' },
]

type Props = {
  caseId: string
  onCaseChange: (caseId: string) => void
  onOpenTraceExplorer: (caseId: string, spanId?: string) => void
}

export default function FailureAnalysis({
  caseId,
  onCaseChange,
  onOpenTraceExplorer,
}: Props) {
  const [report, setReport] = useState<EvaluationSnapshot | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    const controller = new AbortController()

    async function loadReport() {
      setLoading(true)
      setError(null)
      setReport(null)

      try {
        const url =
          `${import.meta.env.BASE_URL}demo-evaluations/${caseId}.json`

        const response = await fetch(url, {
          signal: controller.signal,
        })

        if (!response.ok) {
          throw new Error(`Unable to load evaluation: ${caseId}`)
        }

        const data = (await response.json()) as EvaluationSnapshot

        if (data.caseId !== caseId) {
          throw new Error('Evaluation snapshot identity mismatch')
        }

        if (!controller.signal.aborted) {
          setReport(data)
        }
      } catch (cause) {
        if (!controller.signal.aborted) {
          setError(
            cause instanceof Error
              ? cause.message
              : 'Unknown evaluation loading error',
          )
        }
      } finally {
        if (!controller.signal.aborted) {
          setLoading(false)
        }
      }
    }

    void loadReport()

    return () => controller.abort()
  }, [caseId])

  const findings = report?.attribution.ruleReport.observations ?? []
  const hypotheses = report?.attribution.ruleReport.hypotheses ?? []
  const warnings = report?.attribution.warnings ?? []

  return (
    <div className="space-y-6">
      <div>
        <div className="mb-2 flex items-center gap-2 text-sm text-blue-400">
          <FileSearch size={17} />
          HEAE Rule-Based Analysis
        </div>

        <h2 className="text-2xl font-bold md:text-3xl">
          Failure Analysis
        </h2>

        <p className="mt-2 max-w-3xl text-sm leading-7 text-slate-400">
          Explore classifications generated by the actual HEAE backend,
          including supporting observations, span evidence and attribution
          limitations.
        </p>
      </div>

      <div className="rounded-xl border border-amber-400/20 bg-amber-400/5 p-4 text-sm text-amber-200">
        Recorded synthetic development evaluation. Rule-only mode.
        The LLM judge was not executed.
      </div>

      <div className="flex flex-wrap items-center justify-between gap-4 rounded-xl border border-white/10 bg-[#111b2f] p-4">
        <div className="flex flex-wrap items-center gap-3">
          <label htmlFor="analysis-case" className="text-sm font-medium">
            Evaluation case
          </label>

          <select
            id="analysis-case"
            value={caseId}
            onChange={(event) => onCaseChange(event.target.value)}
            className="rounded-lg border border-white/15 bg-[#17243d] px-3 py-2 text-sm text-white"
          >
            {cases.map((item) => (
              <option key={item.id} value={item.id}>
                {item.id} — {item.label}
              </option>
            ))}
          </select>
        </div>

        <button
          onClick={() => onOpenTraceExplorer(caseId)}
          className="flex items-center gap-2 rounded-lg border border-blue-400/25 bg-blue-400/10 px-4 py-2 text-sm font-medium text-blue-300 hover:bg-blue-400/20"
        >
          Open Trace Explorer
          <ArrowRight size={16} />
        </button>
      </div>

      {loading && (
        <p className="text-sm text-slate-400">
          Loading recorded HEAE evaluation...
        </p>
      )}

      {error && (
        <div role="alert" className="rounded-xl border border-rose-400/30 bg-rose-400/5 p-4 text-sm text-rose-300">
          {error}
        </div>
      )}

      {report && !loading && (
        <>
          <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
            {[
              {
                label: 'Task outcome',
                value: report.summary.outcome.toUpperCase(),
              },
              {
                label: 'Detected categories',
                value:
                  report.summary.categories.join(', ') || 'None assigned',
              },
              {
                label: 'Rule observations',
                value: String(report.summary.observationCount),
              },
              {
                label: 'LLM judge',
                value: report.summary.judgeStatus,
              },
            ].map((item) => (
              <div
                key={item.label}
                className="rounded-xl border border-white/10 bg-[#111b2f] p-5"
              >
                <p className="text-xs text-slate-400">{item.label}</p>
                <p className="mt-3 break-words text-xl font-bold capitalize">
                  {item.value}
                </p>
              </div>
            ))}
          </div>

          <section className="rounded-2xl border border-white/10 bg-[#111b2f] p-5">
            <div className="mb-5 flex items-center gap-2">
              <ShieldAlert size={20} className="text-blue-400" />
              <h3 className="text-lg font-semibold">
                Rule observations
              </h3>
            </div>

            {findings.length === 0 ? (
              <div className="flex items-start gap-3 rounded-xl border border-white/10 bg-[#0b1425] p-5">
                <CheckCircle2
                  size={22}
                  className="shrink-0 text-emerald-400"
                />
                <div>
                  <p className="font-semibold">
                    No deterministic finding
                  </p>
                  <p className="mt-2 text-sm leading-6 text-slate-400">
                    HEAE did not assign a failure category for this
                    execution. This does not mean the task succeeded
                    or that no underlying problem exists.
                  </p>
                </div>
              </div>
            ) : (
              <div className="space-y-4">
                {findings.map((finding, index) => (
                  <div
                    key={`${finding.ruleId}-${index}`}
                    className="rounded-xl border border-amber-400/20 bg-[#0b1425] p-5"
                  >
                    <div className="flex flex-wrap items-center gap-3">
                      <AlertTriangle
                        size={19}
                        className="text-amber-400"
                      />

                      <span className="font-semibold text-amber-300">
                        {finding.ruleId}
                      </span>

                      <span className="rounded-full bg-amber-400/10 px-3 py-1 text-xs capitalize text-amber-300">
                        {finding.category}
                      </span>
                    </div>

                    <p className="mt-4 text-sm leading-7 text-slate-200">
                      {finding.observation}
                    </p>

                    <div className="mt-5">
                      <p className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-400">
                        Rule evidence span IDs
                      </p>

                      <div className="flex flex-wrap gap-2">
                        {finding.evidenceNodeIds.map((id) => (
                            <button
                                key={id}
                                type="button"
                                onClick={() => onOpenTraceExplorer(caseId, id)}
                                title={`Inspect evidence span ${id}`}
                                className="rounded-lg border border-blue-400/20 bg-blue-400/10 px-3 py-2 font-mono text-xs text-blue-300 transition hover:border-blue-400 hover:bg-blue-400/20"
                            >
                                {id} ↗
                            </button>
                         ))}
                      </div>
                    </div>

                    <details className="mt-5">
                      <summary className="cursor-pointer text-sm text-blue-300">
                        View rule metadata
                      </summary>

                      <pre className="mt-3 overflow-auto rounded-lg bg-[#080e1c] p-4 text-xs text-slate-300">
                        {JSON.stringify(finding.details, null, 2)}
                      </pre>
                    </details>
                  </div>
                ))}
              </div>
            )}
          </section>

          <section className="rounded-2xl border border-white/10 bg-[#111b2f] p-5">
            <div className="mb-5 flex items-center gap-2">
              <BrainCircuit size={20} className="text-blue-400" />
              <h3 className="text-lg font-semibold">
                Attribution hypotheses
              </h3>
            </div>

            {hypotheses.length === 0 ? (
              <p className="text-sm leading-7 text-slate-400">
                No attribution hypothesis was generated because the
                rule engine did not produce a supported candidate
                category for further assessment.
              </p>
            ) : (
              <div className="space-y-4">
                {hypotheses.map((hypothesis) => (
                  <div
                    key={hypothesis.category}
                    className="rounded-xl border border-white/10 bg-[#0b1425] p-5"
                  >
                    <div className="flex flex-wrap items-center gap-3">
                      <span className="text-base font-semibold capitalize">
                        {hypothesis.category}
                      </span>

                      <span className="rounded-full border border-amber-400/25 bg-amber-400/10 px-3 py-1 text-xs text-amber-300">
                        {hypothesis.status}
                      </span>
                    </div>

                    <p className="mt-3 text-sm leading-7 text-slate-300">
                      {hypothesis.summary}
                    </p>

                    <p className="mt-3 text-xs text-slate-400">
                      Supporting rules:{' '}
                      {hypothesis.supportingRuleIds.join(', ')}
                    </p>

                    <div className="mt-4 space-y-2">
                      {hypothesis.limitations.map((limitation) => (
                        <p
                          key={limitation}
                          className="flex items-start gap-2 text-xs leading-6 text-slate-400"
                        >
                          <AlertTriangle
                            size={14}
                            className="mt-1 shrink-0 text-amber-400"
                          />
                          {limitation}
                        </p>
                      ))}
                    </div>
                  </div>
                ))}
              </div>
            )}
          </section>

          {warnings.length > 0 && (
            <section className="rounded-xl border border-amber-400/15 bg-amber-400/5 p-5">
              <h3 className="mb-3 text-sm font-semibold text-amber-300">
                Evaluation warnings
              </h3>

              {warnings.map((warning, index) => (
                <p
                  key={index}
                  className="mb-2 text-xs leading-6 text-slate-300"
                >
                  {warning}
                </p>
              ))}
            </section>
          )}

          <div className="break-all rounded-xl border border-white/10 p-4 text-xs leading-6 text-slate-500">
            Trace ID: {report.summary.traceId}
            {' · '}
            Source SHA-256: {report.traceSha256}
            {' · '}
            Provenance: {report.datasetProvenance}
            {' · '}
            Evaluation: {report.evaluationMode}
          </div>
        </>
      )}
    </div>
  )
}
